// Generates site/lib/geo-data.js: station coordinates and simplified country outlines.
// Run by hand when stations change (not in the daily cron):
//   node scripts/build-geo.js trainline-stations.csv ne_50m_admin_0_countries.geojson [site/data/stations.json]
// Sources: trainline-eu/stations (ODbL), Natural Earth 1:50m (public domain).
import { readFile, writeFile } from 'node:fs/promises';

const [stationsCsv, countriesGeojson, onlyStationsJson] = process.argv.slice(2);
const BBOX = [-11, 35, 21, 57]; // lon min, lat min, lon max, lat max
const TOL = 0.025; // simplification tolerance in degrees (~2 km)
const EXTRA = { DEBGB: [52.5486, 13.3885] }; // Berlin-Gesundbrunnen, missing from Trainline

const lines = (await readFile(stationsCsv, 'utf8')).split('\n');
const head = lines[0].split(';');
const col = (n) => head.indexOf(n);
const [iSncf, iLat, iLon] = [col('sncf_id'), col('latitude'), col('longitude')];
const coords = { ...EXTRA };
for (const l of lines.slice(1)) {
  const c = l.split(';');
  if (c[iSncf] && c[iLat]) coords[c[iSncf]] = [Number((+c[iLat]).toFixed(4)), Number((+c[iLon]).toFixed(4))];
}

function simplify(pts) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [x1, y1] = pts[a];
    const [x2, y2] = pts[b];
    const dx = x2 - x1;
    const dy = y2 - y1;
    const len = Math.hypot(dx, dy);
    let max = 0;
    let idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = len < 1e-9
        ? Math.hypot(pts[i][0] - x1, pts[i][1] - y1) // closed ring: distance to the start point
        : Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > TOL) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

if (onlyStationsJson) {
  const keepIds = new Set(JSON.parse(await readFile(onlyStationsJson, 'utf8')).stations.map((s) => s.id));
  for (const id of Object.keys(coords)) if (!keepIds.has(id) && !EXTRA[id]) delete coords[id];
  const missing = [...keepIds].filter((id) => !coords[id]);
  if (missing.length) console.warn('No coordinates for:', missing.join(', '));
}

const gj = JSON.parse(await readFile(countriesGeojson, 'utf8'));
const land = [];
for (const f of gj.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) {
    const ring = poly[0];
    const xs = ring.map((p) => p[0]);
    const ys = ring.map((p) => p[1]);
    if (Math.max(...xs) < BBOX[0] || Math.min(...xs) > BBOX[2] || Math.max(...ys) < BBOX[1] || Math.min(...ys) > BBOX[3]) continue;
    const s = simplify(ring).map(([x, y]) => [Number(x.toFixed(2)), Number(y.toFixed(2))]);
    if (s.length >= 4) land.push({ c: f.properties.ISO_A2_EH || f.properties.ISO_A2, p: s });
  }
}

const out = `// Generated by scripts/build-geo.js. Do not edit by hand.
// Station coordinates: trainline-eu/stations (ODbL). Outlines: Natural Earth (public domain).
export const COORDS = ${JSON.stringify(coords)};
export const LAND = ${JSON.stringify(land)};
`;
await writeFile('site/lib/geo-data.js', out);
console.log(`${Object.keys(coords).length} stations, ${land.length} polygons, ${(out.length / 1024).toFixed(0)} KB`);
